BEGIN;

CREATE TABLE IF NOT EXISTS brands (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text NOT NULL,
  name_ru text,
  name_cn text,
  logo_path text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS brand_aliases (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  brand_id integer NOT NULL REFERENCES brands(id) ON DELETE CASCADE,
  alias_norm text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS model_aliases (
  brand_id integer NOT NULL REFERENCES brands(id) ON DELETE CASCADE,
  source_series text NOT NULL,
  model_name text NOT NULL,
  model_slug text NOT NULL,
  source_url text NOT NULL,
  PRIMARY KEY (brand_id, source_series)
);

CREATE TABLE IF NOT EXISTS unmapped_brand_names (
  raw_name text PRIMARY KEY,
  cars_count integer NOT NULL DEFAULT 1,
  first_seen timestamptz NOT NULL DEFAULT now(),
  last_seen timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE cars ADD COLUMN IF NOT EXISTS brand_id integer REFERENCES brands(id);
ALTER TABLE cars ADD COLUMN IF NOT EXISTS model_name text;
ALTER TABLE cars ADD COLUMN IF NOT EXISTS model_slug text;
ALTER TABLE cars ADD COLUMN IF NOT EXISTS trim text;

CREATE INDEX IF NOT EXISTS cars_brand_id_idx ON cars(brand_id);
CREATE INDEX IF NOT EXISTS cars_brand_model_slug_idx ON cars(brand_id, model_slug);

